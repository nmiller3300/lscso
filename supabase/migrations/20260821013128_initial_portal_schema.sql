create or replace function public.acknowledge_guardian(record_id uuid, response_text text default null)
returns public.guardian_records
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_profile uuid;
  updated_record public.guardian_records;
begin
  current_profile := app_private.current_profile_id();
  if current_profile is null then
    raise exception 'Authorized profile required';
  end if;

  update public.guardian_records
  set
    status = 'Acknowledged',
    acknowledged_at = now(),
    employee_response = nullif(trim(response_text), ''),
    updated_at = now()
  where id = record_id
    and subject_profile_id = current_profile
    and status in ('Issued','Awaiting Acknowledgment')
  returning * into updated_record;

  if updated_record.id is null then
    raise exception 'Guardian record is unavailable for acknowledgment';
  end if;

  return updated_record;
end;
$$;

revoke all on function public.acknowledge_guardian(uuid, text) from public, anon;
grant execute on function public.acknowledge_guardian(uuid, text) to authenticated;

