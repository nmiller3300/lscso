
create schema if not exists app_private;
revoke all on schema app_private from public, anon, authenticated;

create table public.personnel_profiles (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid unique references auth.users(id) on delete set null,
  personnel_id text not null unique check (personnel_id ~ '^LS-[0-9]{3}$'),
  username text,
  display_name text not null check (char_length(display_name) between 2 and 120),
  greeting_name text not null check (char_length(greeting_name) between 2 and 120),
  rank text not null check (rank in (
    'Sheriff','Undersheriff','Major','Captain','1st Lieutenant','Lieutenant',
    'Sergeant','Corporal','Master Deputy','Deputy III','Deputy II','Deputy','Recruit'
  )),
  access_tier text not null check (access_tier in ('Executive','Command','Supervisor','Preliminary','Deputy')),
  call_sign text check (call_sign is null or call_sign ~ '^S-4[0-9]{2}$'),
  division text not null default 'Unassigned',
  supervisor_label text not null default 'Pending command assignment',
  status text not null default 'Active' check (status in ('Active','Acting','Suspended','Deactivated')),
  is_test_account boolean not null default false,
  credentials_assigned boolean generated always as (auth_user_id is not null) stored,
  last_sign_in_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deactivated_at timestamptz,
  deactivated_by uuid references public.personnel_profiles(id)
);

create unique index personnel_profiles_username_unique
  on public.personnel_profiles (lower(username))
  where username is not null;

create unique index personnel_profiles_active_call_sign_unique
  on public.personnel_profiles (call_sign)
  where call_sign is not null and status <> 'Deactivated';

create table public.call_sign_assignments (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.personnel_profiles(id) on delete restrict,
  call_sign text not null check (call_sign ~ '^S-4[0-9]{2}$'),
  assigned_at timestamptz not null default now(),
  assigned_by uuid references public.personnel_profiles(id),
  released_at timestamptz,
  released_by uuid references public.personnel_profiles(id),
  release_reason text,
  created_at timestamptz not null default now(),
  check (released_at is null or released_at >= assigned_at)
);

create unique index call_sign_assignments_active_unique
  on public.call_sign_assignments (call_sign)
  where released_at is null;

create index call_sign_assignments_profile_idx
  on public.call_sign_assignments (profile_id, assigned_at desc);

create table public.division_assignments (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.personnel_profiles(id) on delete cascade,
  division text not null,
