create or replace function app_private.current_profile_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select p.id
  from public.personnel_profiles p
  where p.auth_user_id = (select auth.uid())
    and p.status in ('Active','Acting')
  limit 1
$$;

create or replace function app_private.current_access_tier()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.access_tier
  from public.personnel_profiles p
  where p.auth_user_id = (select auth.uid())
    and p.status in ('Active','Acting')
  limit 1
$$;

create or replace function app_private.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function app_private.write_audit_log()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_profile uuid;
  row_id text;
begin
  select p.id into actor_profile
  from public.personnel_profiles p
  where p.auth_user_id = (select auth.uid())
  limit 1;

  row_id := coalesce((case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end)->>'id', null);

  insert into public.audit_log (
    actor_user_id,
    actor_profile_id,
    action,
    table_name,
    record_id,
    old_data,
    new_data
  ) values (
    (select auth.uid()),
    actor_profile,
    tg_op,
    tg_table_schema || '.' || tg_table_name,
    row_id,
    case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) else null end,
    case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) else null end
  );

  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

